#!/usr/bin/env python3
"""Write `pt_docs/skills.rst`, the table of every skill, from the SKILL.md frontmatter.

`pt_docs/` is this repo's page in the PyTerrier docs (readthedocs copies it like any extension's
`pt_docs/`). The table covers the merged skill set from `tests/skill_files.py::find_skills`, so skills
collected into `skills/ext/` appear with the package they came from. `tests/test_pt_docs.py` fails when
the committed file is out of date.

Examples
    python scripts/build_pt_docs.py           # rewrite pt_docs/skills.rst
    python scripts/build_pt_docs.py --check   # exit 1 if it is out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "tests"))
from skill_files import EXT_SKILLS_DIR, find_skills, read_frontmatter  # noqa: E402

SKILLS_RST = REPO / "pt_docs" / "skills.rst"

HEADER = """\
..
   Generated by scripts/build_pt_docs.py from the SKILL.md frontmatter. Do not edit by hand.

Skills
=================================================

Each skill is a folder with a ``SKILL.md`` that the agent reads when the task matches its
description. Install all of them at once (see :doc:`usage`); the agent picks the relevant ones.
``pyterrier-basics`` is the base skill that every other skill assumes.

"""


def rst_text(text: str) -> str:
    """One line of RST cell text. Markdown `code` becomes an RST literal; markup characters are escaped."""
    parts = " ".join(text.split()).replace("``", "`").split("`")
    for i in range(0, len(parts), 2):  # outside literals: *, ** and |x| would start RST markup
        parts[i] = parts[i].replace("\\", "\\\\").replace("*", "\\*").replace("|", "\\|")
    for i in range(1, len(parts), 2):
        parts[i] = f"``{parts[i]}``"
    return "".join(parts)


def render() -> str:
    manifest_path = EXT_SKILLS_DIR / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    rows = []
    for skill in find_skills():
        meta = read_frontmatter(skill)
        name = meta["name"]
        source = f"``{manifest[name]['package']}``" if skill.is_relative_to(EXT_SKILLS_DIR) else "this repo"
        rows.append((f"``{name}``", rst_text(meta["description"]), rst_text(meta["compatibility"]), source))

    lines = [HEADER, ".. list-table::", "   :header-rows: 1", "   :widths: 15 55 20 10", ""]
    for row in [("Skill", "When the agent uses it", "Checked with", "From"), *rows]:
        lines.append(f"   * - {row[0]}")
        lines += [f"     - {cell}" for cell in row[1:]]
    lines += [
        "",
        f"{len(rows)} skills. Skills marked with a package come from that extension's ``pt_skills/``",
        "folder (see :doc:`authoring`) and replace a skill of the same name from this repo.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 if pt_docs/skills.rst is out of date")
    args = ap.parse_args()
    text = render()
    if args.check:
        current = SKILLS_RST.read_text(encoding="utf-8") if SKILLS_RST.exists() else ""
        if current != text:
            sys.exit(f"{SKILLS_RST.relative_to(REPO)} is out of date: run python scripts/build_pt_docs.py")
        return
    SKILLS_RST.write_text(text, encoding="utf-8")
    print(f"wrote {SKILLS_RST.relative_to(REPO)}")


if __name__ == "__main__":
    main()
